CREATE TABLE IF NOT EXISTS teeko_classroom_journal (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  classroom_id uuid NOT NULL REFERENCES teeko_classrooms(id) ON DELETE CASCADE,
  event_key text NOT NULL CHECK (length(event_key) BETWEEN 1 AND 200),
  connection_epoch integer NOT NULL CHECK (connection_epoch >= 0),
  revision integer NOT NULL CHECK (revision >= 0),
  step_index integer NOT NULL CHECK (step_index >= 0),
  kind text NOT NULL CHECK (kind IN ('utterance','interaction','tool','connection','visual')),
  actor text NOT NULL CHECK (actor IN ('child','teacher','application','provider')),
  status text NOT NULL CHECK (status IN ('recorded','requested','confirmed','rejected','failed')),
  name text NOT NULL CHECK (length(name) BETWEEN 1 AND 80),
  text text CHECK (length(text) <= 6000),
  details jsonb NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(details) = 'object' AND octet_length(details::text) <= 32768),
  correlation_id text CHECK (length(correlation_id) <= 200),
  created_at timestamptz NOT NULL,
  UNIQUE (classroom_id,event_key)
);
CREATE INDEX IF NOT EXISTS teeko_classroom_journal_timeline ON teeko_classroom_journal(classroom_id,id);
